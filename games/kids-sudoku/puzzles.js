export function sudokuPeers(index,size,boxRows,boxCols){
 const row=Math.floor(index/size),col=index%size,seen=new Set();
 for(let k=0;k<size;k++){seen.add(row*size+k);seen.add(k*size+col)}
 const r0=Math.floor(row/boxRows)*boxRows,c0=Math.floor(col/boxCols)*boxCols;
 for(let r=r0;r<r0+boxRows;r++)for(let c=c0;c<c0+boxCols;c++)seen.add(r*size+c);
 seen.delete(index);return [...seen];
}
export function sudokuConflicts(cells,level){
 const bad=new Set();
 for(let i=0;i<cells.length;i++){
   const n=Number(cells[i]);if(!n)continue;
   for(const j of sudokuPeers(i,level.size,level.boxRows,level.boxCols))
     if(Number(cells[j])===n){bad.add(i);bad.add(j)}
 }
 return bad;
}
export function sudokuSolved(cells,level){
 return cells.length===level.size**2&&!sudokuConflicts(cells,level).size&&
   cells.every((v,i)=>Number(v)===Number(level.solution[i]));
}
export function countSudokuSolutions(puzzle,level,limit=2){
 const n=level.size,cells=Array.from(puzzle,ch=>Number(ch));let solutions=0;
 const peerSets=Array.from({length:n*n},(_,i)=>sudokuPeers(i,n,level.boxRows,level.boxCols));
 function search(){
   let target=-1,choices=[];
   for(let i=0;i<cells.length;i++){
     if(cells[i])continue;
     const used=new Set(peerSets[i].map(j=>cells[j]).filter(Boolean));
     const opts=Array.from({length:n},(_,j)=>j+1).filter(d=>!used.has(d));
     if(!opts.length)return;
     if(target<0||opts.length<choices.length){target=i;choices=opts;if(opts.length===1)break}
   }
   if(target<0){solutions++;return}
   for(const candidate of choices){cells[target]=candidate;search();cells[target]=0;if(solutions>=limit)return}
 }
 search();return solutions;
}
