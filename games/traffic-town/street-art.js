export const trafficStreetBySign = new Map(Object.entries(settings).flatMap(([setting, titles]) =>
  titles.map(title => [title, setting])
));

const backdrops = new URL("../../assets/world-motion/backgrounds/", import.meta.url);

export function trafficStreetScene(title) {
  const setting = trafficStreetBySign.get(title) ?? "neighborhood";
  const image = new URL(`traffic-${setting}.webp`, backdrops).href;
  return `<div class="traffic-street-scene" data-setting="${setting}">
    <img class="traffic-street-backdrop" src="${image}" width="832" height="468" alt="" decoding="async">
    <div class="traffic-sign-model">${trafficSignSvg(title)}</div>
  </div>`;
}
