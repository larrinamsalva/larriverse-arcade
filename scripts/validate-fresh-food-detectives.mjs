import assert from "node:assert/strict";
import fs from "node:fs";
import { CHAPTERS, SAMPLE_BAKERY, PRODUCTS, LEVELS } from "../games/fresh-food-detectives/levels.js";

assert.equal(CHAPTERS.length,12);
assert.equal(LEVELS.length,120);
assert.ok(PRODUCTS.length>=45);
assert.equal(new Set(LEVELS.map(level=>level.id)).size,120);
assert.ok(LEVELS.every((level,index)=>level.chapter===Math.floor(index/10)));
assert.ok(LEVELS.every(level=>level.product&&level.product.name&&level.product.kind));
assert.ok(LEVELS.every(level=>Array.isArray(level.options)&&level.options.length===4));
assert.ok(LEVELS.every(level=>Number.isInteger(level.answer)&&level.answer>=0&&level.answer<4));
assert.ok(LEVELS.every(level=>level.prompt.length>25&&level.explanation.length>35));
assert.equal(LEVELS.filter(level=>level.chapter===8).length,10);
assert.ok(LEVELS.filter(level=>level.chapter===8).every(level=>/SAMPLE Sunny Bakery|sample bakery/i.test(level.prompt)));
assert.ok(LEVELS.filter(level=>level.chapter===8).every(level=>/Real bakeries can use different systems/i.test(level.explanation)));
assert.ok(/real bakeries and stores may use different colors/i.test(SAMPLE_BAKERY.note));
assert.equal(SAMPLE_BAKERY.colors.length,5);
assert.ok(LEVELS.filter(level=>level.chapter===9).every(level=>/LOT|BATCH|LINE|manufacturer/i.test(level.visualLabel+" "+level.prompt+" "+level.explanation)));
const game=fs.readFileSync("games/fresh-food-detectives/game.js","utf8");
const css=fs.readFileSync("games/fresh-food-detectives/game.css","utf8");
const html=fs.readFileSync("games/fresh-food-detectives/index.html","utf8");
assert.match(game,/larriverse\.freshFoodDetectives\.v1/);
assert.match(game,/activitiesCompleted/);
assert.match(css,/food-model/);
assert.match(css,/transform-style:preserve-3d/);
assert.match(css,/kind-bread/);
assert.match(css,/kind-can/);
assert.match(css,/kind-jar/);
assert.match(css,/kind-bottle/);
assert.match(html,/120 levels/);
assert.match(html,/bread-tie colors are only useful/i);
assert.doesNotMatch(LEVELS.map(level=>level.prompt+" "+level.explanation).join("\n"),/bread tie colors are universal|always means monday/i);
console.log("Fresh Food Detectives validation passed: 120 levels, 12 chapters, "+PRODUCTS.length+" package models.");